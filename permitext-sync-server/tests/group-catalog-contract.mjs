import assert from 'node:assert/strict';
import { sharedGroup, mergeGroupCatalogs, applySharedGroups } from '../public/group-catalog.js';
import { mergeContinuityRecords } from '../continuity-merge.mjs';
const group={id:'g',name:'Review',paneIDs:['reader:a'],collapsed:true,columns:{'reader:a':{kind:'reader',value:{id:'a',chapterID:'ch',codePrefix:'BC',scrollTop:900},width:800,position:{top:20},draft:'private'}}};
const shared=sharedGroup(group);
assert.equal(shared.columns['reader:a'].width,undefined);
assert.equal(shared.columns['reader:a'].draft,undefined);
assert.equal(shared.columns['reader:a'].value.scrollTop,undefined);
assert.equal(shared.columns['reader:a'].value.codePrefix,'BC');
const a={...shared,workspaceID:'w',order:0,updatedAt:'2026-09-14T10:00:00Z',deleted:false};
const b={...a,id:'other',order:1};
assert.equal(mergeGroupCatalogs([a],[b]).length,2);
const removed={...a,deleted:true,updatedAt:'2026-09-14T11:00:00Z'};
assert.equal(mergeGroupCatalogs([removed],[a])[0].deleted,true);
const renamed={...a,name:'Renamed',updatedAt:'2026-09-14T12:00:00Z'};
const applied=applySharedGroups([group],[renamed])[0];
assert.equal(applied.name,'Renamed');assert.equal(applied.columns['reader:a'].width,800);assert.equal(applied.collapsed,true);
assert.equal(applySharedGroups([],[a])[0].columns['reader:a'].width,undefined);
const merged=mergeContinuityRecords({updatedAt:a.updatedAt,values:{workspaceGroupsJSON:JSON.stringify([a])}},{updatedAt:renamed.updatedAt,values:{}});
assert.equal(JSON.parse(merged.values.workspaceGroupsJSON)[0].id,'g');
assert.equal(mergeGroupCatalogs([a],[{...a,workspaceID:'other'}]).length,2);
console.log('Group sync: merge, rename, deletion, workspace isolation, iOS preservation and local layout retention passed.');
