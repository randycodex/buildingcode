import assert from "node:assert/strict";
import vm from "node:vm";
import { readFile } from "node:fs/promises";
import { createActiveCodeSourceController } from "../public/active-code-source-controller.js";
import { createActiveCodeSourcePreferences } from "../public/active-code-sources.js";
const text = await readFile(new URL("../public/app.js", import.meta.url), "utf8");
const start = text.indexOf("async function enabledReaderBrowseProjection(");
const end = text.indexOf("\nfunction renderReaderSourceRecovery", start);
const values = new Map();
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
const a = { canonicalEdition: "2022", jurisdictionID: 1, codeID: 1, categoryID: 1, codePrefix: "BC" };
const b = { ...a, canonicalEdition: "2014", categoryID: 2 };
let loads = 0;
const controller = createActiveCodeSourceController({ storage, loadCatalog: async () => { loads++; return [a, b]; } });
controller.setContext({ accountID: null, sessionID: "one" });
const context = vm.createContext({ activeCodeSourcesController: controller, codeOptionVersion: code => code.version, accountContextChangedError: () => new Error("changed") });
vm.runInContext(text.slice(start, end) + "\nthis.project = enabledReaderBrowseProjection;", context);
const codes = [{ prefix: "BC", version: "2022" }, { prefix: "BC", version: "2014" }];
const currentReader = { codePrefix: "BC", codeVersion: "2022", chapterID: "33", scrollTop: 180 };
const original = JSON.stringify({ codes, currentReader });
assert.equal((await context.project(codes)).codes.length, 2);
assert.equal(loads, 0);
createActiveCodeSourcePreferences(storage).update(null, a, false);
controller.reload();
assert.deepEqual(Array.from((await context.project(codes)).codes), [codes[1]]);
assert.equal((await context.project([codes[0]])).codes.length, 0);
assert.equal(JSON.stringify({ codes, currentReader }), original);
createActiveCodeSourcePreferences(storage).update(null, b, false);
controller.reload();
assert.equal((await context.project(codes)).codes.length, 0);
values.set("permitext.active-code-sources.v1.guest", "broken"); controller.reload();
await assert.rejects(context.project(codes), /unavailable/);
assert.equal(JSON.stringify({ codes, currentReader }), original);
console.log("Reader Browse projection passed: lazy default, exact edition filtering, all-off/error, raw catalog and current Reader unchanged.");
