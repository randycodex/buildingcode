import assert from 'node:assert/strict';
import {mountAssistantColumn} from '../public/assistant-column.js';
import {documentFixture} from './helpers/workflow-dom.mjs';
const doc = documentFixture(), panel = doc.createElement('article'), header = doc.createElement('header');
panel.dataset.paneId = 'utility:analysis:one'; header.className = 'panel-header';
const actions = doc.createElement('div'); actions.className = 'panel-actions'; header.append(actions); panel.append(header);
const history = doc.createElement('aside'), body = doc.createElement('section'), draft = doc.createElement('textarea');
history.scrollTop = 110; draft.value = 'Unsent question'; body.scrollTop = 340; body.append(draft); panel.append(history, body);
const state = {}; let changes = 0;
const column = mountAssistantColumn({panel, history, body, state, changed: () => changes++});
const sources = panel.querySelector('.assistant-sources-view'), menu = panel.querySelector('.assistant-history-menu');
const tabs = panel.querySelector('.assistant-view-tabs').children;
assert.equal(state.assistantView, 'sources'); assert.equal(body.hidden, true); assert.equal(sources.hidden, false);
assert.equal(history.parentNode, menu, 'History lives only in the header dropdown.');
assert.equal(body.children[0], draft);
const material = doc.createElement('section'); material.className = 'assistant-materials'; material.dataset.count = '4';
column.setMaterials(material); assert.equal(tabs[1].textContent, 'Sources · 4');
tabs[0].dispatch('click'); assert.equal(body.hidden, false); assert.equal(sources.hidden, true);
assert.equal(tabs[0].attributes['aria-selected'], 'true'); assert.equal(tabs[1].tabIndex, -1);
tabs[1].dispatch('click'); tabs[0].dispatch('click');
assert.equal(draft.value, 'Unsent question'); assert.equal(body.children[0], draft); assert.equal(body.scrollTop, 340);
assert.equal(history.scrollTop, 110); assert.equal(sources.children[0], material, 'Switching retains an unapplied source picker.');
material.dataset.count = '2'; material.dispatch('assistant-material-state', {bubbles: true});
assert.equal(tabs[1].textContent, 'Sources · 2'); assert.equal(body.hidden, false, 'Source acknowledgments do not change the selected view.');
let prevented = false;
tabs[0].dispatch('keydown', {key: 'ArrowRight', preventDefault() {prevented = true;}});
assert.ok(prevented); assert.equal(doc.activeElement, tabs[1]); assert.equal(state.assistantView, 'sources');
menu.open = true; let stopped = false;
menu.dispatch('keydown', {key: 'Escape', preventDefault() {}, stopPropagation() {stopped = true;}});
assert.ok(stopped); assert.equal(menu.open, false); assert.equal(doc.activeElement, menu.children[0]);
menu.open = true; panel.dispatch('pointerdown', {target: draft}); assert.equal(menu.open, false);
const newChat = doc.createElement('button'); newChat.className = 'research-new-chat'; history.append(newChat);
menu.open = true; newChat.dispatch('click', {bubbles: true}); assert.equal(menu.open, false);
const replacement = doc.createElement('section'); replacement.className = 'assistant-materials'; replacement.dataset.count = '0';
column.setMaterials(replacement); assert.equal(material.parentNode, null); assert.equal(sources.children.length, 1); assert.equal(tabs[1].textContent, 'Sources · 0');
assert.ok(changes >= 5);
console.log('Assistant tabs retain draft, thread, picker and scroll; count acknowledgments, header history and keyboard navigation passed.');
