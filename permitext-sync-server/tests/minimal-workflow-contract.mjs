import assert from 'node:assert/strict';
import {normalizeVisitedWorkflowViews, shouldOpenNotebookByDefault, initialReportOutlineHidden, showProjectFact} from '../public/minimal-workflow.js';
import {normalizeNotebookQuestions, notebookQuestionsText} from '../public/notebook-questions.js';
import {captureWorkspaceLayout, applyWorkspaceLayout} from '../public/workspace-state.js';
assert.deepEqual(normalizeVisitedWorkflowViews({}),[]);
assert.equal(shouldOpenNotebookByDefault('notebook',[]),true);
assert.equal(shouldOpenNotebookByDefault('research',[]),false);
assert.equal(shouldOpenNotebookByDefault('notebook',normalizeVisitedWorkflowViews({workflowView:'research'})),false,'Legacy intentionally closed Notes must remain closed');
const layout={}; applyWorkspaceLayout(layout,captureWorkspaceLayout({workflowVisitedViews:['research'],workflowView:'research'}));
assert.deepEqual(layout.workflowVisitedViews,['research']);
assert.equal(initialReportOutlineHidden([]),true);
assert.equal(initialReportOutlineHidden([{kind:'heading'},{kind:'paragraph'}]),true);
assert.equal(initialReportOutlineHidden([{kind:'heading'},{kind:'heading'}]),false);
assert.equal(showProjectFact({key:'occupancy'},null),true);
assert.equal(showProjectFact({key:'height'},null),false);
assert.equal(showProjectFact({key:'height'},{status:'unknown'}),true);
assert.equal(showProjectFact({key:'height'},null,{all:true}),true);
const q={id:'q',text:'Verify condition',why:'Needed for interpretation',status:'open',resolution:''};
assert.deepEqual(normalizeNotebookQuestions([q]),[q]);
assert.throws(()=>normalizeNotebookQuestions([{...q,status:'resolved'}]),/resolution/);
assert.throws(()=>normalizeNotebookQuestions([q,q]),/unique/);
assert.throws(()=>normalizeNotebookQuestions([{...q,text:'x'.repeat(1001)}]),/question/);
assert.match(notebookQuestionsText([{...q,status:'resolved',resolution:'Source reviewed'}]),/does not certify compliance/);
console.log('Minimal workflow contracts passed: fresh defaults, legacy preservation, persisted view visits, contextual outline, complete facts access, question validation.');
