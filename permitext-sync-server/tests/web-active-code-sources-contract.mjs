import assert from 'node:assert/strict';
import {createActiveCodeSources, decodeActiveCodeSources, codeSourceKey, createActiveCodeSourcePreferences} from '../public/active-code-sources.js';
const a={canonicalEdition:'canonical:2022',jurisdictionID:1,codeID:1,categoryID:1};
const b={...a,canonicalEdition:'canonical:2014'};
const c={...a,categoryID:2};
const initial=decodeActiveCodeSources(null);
assert.equal(initial.isEnabled(a),true);
const disabled=initial.withEnabled(a,false);
assert.equal(initial.isEnabled(a),true);
assert.equal(disabled.isEnabled(a),false);
assert.equal(disabled.isEnabled(b),true);
assert.equal(disabled.isEnabled(c),true);
assert.deepEqual(disabled.enabledSources([c,b,c,a]),[b,c]);
assert.equal(disabled.scopeKey([c,b,c,a]),disabled.scopeKey([b,c]));
assert.deepEqual(decodeActiveCodeSources(disabled.serialize()).disabledSources(),[a]);
assert.deepEqual(disabled.enabledSources([]),[]);
assert.equal(decodeActiveCodeSources(disabled.serialize()).isEnabled(a),false,'Absent installed source retains preference');
assert.equal(disabled.withEnabled(a,true).isEnabled(a),true);
assert.equal(codeSourceKey({...a}),codeSourceKey(a));
for(const input of ['', 'null','{}','{"version":2,"disabledSources":[]}','{"version":1,"disabledSources":null}',42,'{"version":1,"disabledSources":[{}]}']) assert.throws(()=>decodeActiveCodeSources(input));
for(const source of [{...a,categoryID:1.5},{...a,codeID:NaN},{...a,jurisdictionID:Number.MAX_SAFE_INTEGER+1},{...a,canonicalEdition:''}]) assert.throws(()=>createActiveCodeSources([source]));
assert.throws(()=>disabled.withEnabled(a,'false'));
