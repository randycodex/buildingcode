const prefs=createActiveCodeSourcePreferences(storage);
for(const id of [null,'guest','', 'a',' a','é','e\u0301','account."guest"']) {
 prefs.update(id,a,false);
 assert.equal(prefs.load(id).isEnabled(a),false);
 prefs.update(id,a,true);
 assert.equal(prefs.load(id).isEnabled(a),true);
}
assert.equal(values.size,8,'Exact account keys remain separate');
