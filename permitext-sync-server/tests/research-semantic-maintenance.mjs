import assert from "node:assert/strict";
import { planSemanticRefresh, assertRefreshBudget } from "../scripts/refresh-prepared-research-assets.mjs";
import { researchPassageEmbeddingText, researchSemanticInputHash } from "../research-semantic-passages.mjs";
const passage = { codePrefix: "ZR", codeEdition: "current", sectionNumber: "81-745", title: "Theater rehabilitation", text: "Public enacted wording." };
const hash = researchSemanticInputHash(researchPassageEmbeddingText(passage));
const vector = Float32Array.from({ length: 256 }, (_, index) => index === 0 ? 1 : 0);
const changed = { ...passage, text: "New enacted wording." };
const index = { fingerprint: "a".repeat(64), passages: [passage, passage, changed] };
const plan = planSemanticRefresh(index, { vectors: new Map([[hash, vector]]) });
assert.equal(plan.summary.inputCount, 2);
assert.equal(plan.summary.reusedInputCount, 1);
assert.equal(plan.summary.missingInputCount, 1);
assert.equal(plan.retained.get(hash), vector, "Reuse the exact cached Float32 vector");
assert.equal(plan.batches[0][0][1], researchPassageEmbeddingText(changed));
assert.throws(() => planSemanticRefresh(index, { vectors: new Map() }, 0), /batch size/);
assertRefreshBudget(plan, 0.5);
assert.throws(() => assertRefreshBudget(plan, 0.51), /at most/);
assert.throws(() => assertRefreshBudget(plan, 0), /positive/);
assert.throws(() => assertRefreshBudget({ summary: { conservativeReservationUSD: 0.50001 } }, 0.5), /before provider dispatch/);
console.info("Semantic maintenance: exact cache reuse, changed-input inventory, deduplication, and pre-dispatch spending bounds passed; no provider calls.");
