import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const source=await readFile(new URL('../src/notebook-editor.js',import.meta.url),'utf8');
const mount=source.slice(source.indexOf('export function mountPermitextNotebookEditor')).replace('export function','function');
const calls=[];
let docJSON={type:"doc",content:[{type:"paragraph",attrs:{id:"generated-a"},content:[{type:"text",text:"Original content"}]}]};
const editor={_tiptapEditor:{state:{selection:{from:41,to:47},doc:{content:{size:100},toJSON:()=>docJSON}},commands:{setTextSelection:p=>calls.push(['selection',p]),focus:(p,o)=>calls.push(['focus',p,o])}}};
class HTMLElement {}
let ref;
const context=vm.createContext({HTMLElement,React:{createElement:(_component,props)=>props},PermitextNotebookEditor(){},createRoot:()=>({render(props){ref=props.controllerRef;ref.current=editor;},unmount(){ref.current=null;}})});
vm.runInContext(mount,context);
const controller=context.mountPermitextNotebookEditor(new HTMLElement());
const saved=controller.getEditingPosition();
assert.equal(saved.from,41);assert.equal(saved.to,47);
docJSON.content[0].attrs.id="regenerated-b";
assert.equal(controller.restoreEditingPosition(saved),true,'same content survives regenerated block IDs');
assert.equal(JSON.stringify(calls),JSON.stringify([['selection',{from:41,to:47}],['focus',undefined,{scrollIntoView:false}]]));
for(const position of [null,{from:-1,to:4},{from:3,to:101},{from:9,to:2},{from:NaN,to:4},{from:1.5,to:4}])assert.equal(controller.restoreEditingPosition(position && {...saved,...position}),false);
assert.equal(calls.length,2,'invalid/stale positions do not mutate the editor');
docJSON.content[0].content[0].text="Replaced content";
assert.equal(controller.restoreEditingPosition(saved),false,'changed text rejects still-in-bounds offsets');
docJSON.content[0].content[0].text="Original content";
docJSON.content[0].type="heading";
assert.equal(controller.restoreEditingPosition(saved),false,'changed structure rejects old offsets');
assert.equal(calls.length,2,'changed documents never receive selection/focus commands');
controller.destroy();
assert.equal(controller.getEditingPosition(),null);
assert.equal(controller.restoreEditingPosition({from:2,to:2}),false);
console.log('Notebook editing-position controller: selection range, no-scroll focus, document binding, invalid bounds, unmounted guard PASS');
