import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../public/app.js',import.meta.url),'utf8');
const start=source.indexOf('const readerSplitHTMLCache'),end=source.indexOf('\nfunction splitAnnotatedCodeBlock',start);
let parses=0;
const context=vm.createContext({annotatedBlocksForSection(section){parses++;return [{id:'stable-id',plainText:section.blocks[0].html}];}});
vm.runInContext(source.slice(start,end),context);
const block={kind:'html',id:'s1',html:'Exact enacted text'.repeat(2300),assetRevision:'rev1'};
const section={id:'section',blocks:[block]};
const first=context.readerAnnotatedBlocksForSection(section);first[0].plainText='caller mutation';
const second=context.readerAnnotatedBlocksForSection(section);assert.equal(parses,1);assert.equal(second[0].plainText,block.html,'Cached public fragments are not mutable through returned blocks');
context.readerAnnotatedBlocksForSection({...section,blocks:[{...block,assetRevision:'rev2'}]});assert.equal(parses,2,'Asset revision invalidates parsed fragments');
for(let i=0;i<12;i++)context.readerAnnotatedBlocksForSection({...section,blocks:[{...block,html:block.html+i}]});
context.readerAnnotatedBlocksForSection(section);assert.equal(parses,15,'LRU drops old sources instead of retaining them for every Reader');
console.log('Public split cache: exact fragment identity, isolated returned objects, corpus asset revision and bounded LRU passed.');
