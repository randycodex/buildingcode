import assert from 'node:assert/strict';
import vm from 'node:vm';
import { createServer } from 'node:http';
import { randomUUID } from 'node:crypto';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { researchRecoveryFromFailedMessage } from '../public/research-progress.js';
import { activeResearchMessages } from '../research-context-state.mjs';
for (const key of Object.keys(process.env)) if (/^(PERMITEXT_|OPENAI_|VERCEL|DATABASE_URL$|STORAGE_URL$|POSTGRES_URL$|NEON_DATABASE_URL$)/.test(key)) delete process.env[key];
const scratch = await mkdtemp(join(tmpdir(), 'permitext-failed-question-'));
Object.assign(process.env, { NODE_ENV: 'test', PERMITEXT_SYNC_DATA_PATH: join(scratch, 'store.json'), PERMITEXT_LOCAL_PRIVATE_ASSET_PATH: join(scratch, 'assets'), PERMITEXT_ALLOW_WEB_BROWSER_SIGN_IN: '1', PERMITEXT_SYNC_GRANT_ADMIN_TOKEN: randomUUID(), PERMITEXT_EVIDENCE_DISCOVERY_BETA: '1' });
const actualFetch = globalThis.fetch;
globalThis.fetch = () => { throw new Error('External requests prohibited'); };
let server;
try {
  const { handleRequest, researchConversationWithFailedQuestion, appendCompletedResearchExchange } = await import('../app.mjs');
  const fixture = { id: 'fixture', revision: 4, contextRevision: 0, title: 'Preserved title', messages: [], sources: [], primaryProjectID: 'project', createdAt: new Date().toISOString() };
  const details = { userID: 'u', requestID: 'r', question: 'Preserve question', contextRevision: 0, projectID: 'project', startedAt: fixture.createdAt, code: 'INVALID_RESEARCH_RESPONSE' };
  const failed = researchConversationWithFailedQuestion(fixture, details);
  assert.equal(failed.messages.length, 1);
  assert.equal(fixture.messages.length, 0);
  assert.equal(failed.revision, 4);
  assert.equal(activeResearchMessages(failed).length, 0, 'Failed prompts cannot influence subsequent answers');
  assert.match(failed.messages[0].failure.message, /complete answer/);
  assert.equal(researchConversationWithFailedQuestion({ ...fixture, contextRevision: 1 }, details), null);
  assert.equal(researchConversationWithFailedQuestion({ ...fixture, primaryProjectID: 'other' }, details), null);
  assert.equal(researchConversationWithFailedQuestion(null, details), null);
  const completed = structuredClone(failed);
  appendCompletedResearchExchange(completed, { ...failed.messages[0], failure: undefined }, { id: 'answer', role: 'assistant', researchRequestID: 'r', answer: {} });
  assert.equal(completed.messages.length, 2);
  assert.equal(researchConversationWithFailedQuestion(completed, details), null, 'Late failure cannot replace successful answer');
  assert.equal(researchConversationWithFailedQuestion(failed, { ...details, question: 'Different question' }), null);
  const twice = researchConversationWithFailedQuestion(failed, details);
  assert.equal(twice.messages.length, 1);
  server = createServer(handleRequest);
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const request = async (path, body, token) => {
    const response = await actualFetch(`http://127.0.0.1:${server.address().port}${path}`, { method: 'POST', headers: { 'content-type': 'application/json', ...(token ? { authorization: `Bearer ${token}` } : {}) }, body: JSON.stringify(body) });
    return { status: response.status, body: await response.json() };
  };
  const signed = await request('/account/sign-in', { credential: { provider: 'web', providerUserID: randomUUID(), displayName: 'Failure history fixture' } });
  const token = signed.body.account.backendSessionToken;
  const auth = { accountUserID: signed.body.account.appUserID };
  await request('/admin/lifetime-grants/grant', { userID: auth.accountUserID }, process.env.PERMITEXT_SYNC_GRANT_ADMIN_TOKEN);
  const created = await request('/research/conversations/create', { auth }, token);
  assert.equal(created.status, 201, JSON.stringify(created.body));
  const conversationID = created.body.conversation.id;
  const requestID = randomUUID();
  const question = 'What does NYC Building Code 2022 Section 1012 require for ramps?';
  const first = await request('/research/conversations/message', { auth, conversationID, question, requestID }, token);
  assert.equal(first.status, 503, JSON.stringify(first.body));
  assert(['RESEARCH_NOT_CONFIGURED', 'RESEARCH_SPEND_CAP'].includes(first.body.code), JSON.stringify(first.body));
  const reopened = await request('/research/conversations/get', { auth, conversationID }, token);
  assert.equal(reopened.body.conversation.messages.length, 1);
  const message = reopened.body.conversation.messages[0];
  assert.equal(message.question, question);
  assert.equal(message.requestID, requestID);
  assert.equal(message.failure.status, 'failed');
  const recovery = researchRecoveryFromFailedMessage(message, conversationID);
  assert.equal(recovery.requestID, requestID);
  assert.equal(recovery.question, question);
  const webSource = await readFile(new URL('../public/app.js', import.meta.url), 'utf8');
  const copyStart = webSource.indexOf('function researchFailureMessage(');
  const copyEnd = webSource.indexOf('\n}', copyStart) + 2;
  const copy = vm.runInNewContext('(' + webSource.slice(copyStart, copyEnd) + ')');
  assert.equal(copy({ payload: { code: 'RESEARCH_INTERRUPTED', status: 502 }, message: 'Service unavailable' }),
    'Research was interrupted before an answer was saved. Your question is still here.');
  const restoreStart = webSource.indexOf('function restoreResearchProgressSession(');
  const restoreEnd = webSource.indexOf('\n}', restoreStart) + 2;
  const web = vm.createContext({ Date, Map, AbortController, localStorage: {}, researchRecoveryFromFailedMessage,
    researchRequestRecoveryScope: () => ({ accountUserID: auth.accountUserID, workspaceID: 'web-workspace' }),
    readResearchRequestRecovery: () => null, researchConversationContainsCompletedRequest: () => false,
    activeResearchProgress: new Map(), persistResearchProgressSession: () => true });
  vm.runInContext(webSource.slice(restoreStart, restoreEnd) + ';globalThis.restore = restoreResearchProgressSession;', web);
  const restored = web.restore(reopened.body.conversation);
  assert.equal(restored.id, requestID);
  assert.equal(restored.status, 'failed');
  assert.equal(restored.question, question);
  assert.equal(restored.retry, null, 'Opening history never automatically retries a paid request');
  const storeAfterFailure = JSON.parse(await readFile(join(scratch, 'store.json'), 'utf8'));
  assert(!(storeAfterFailure.researchUsageByUserID?.[auth.accountUserID] || []).some(item => item.mode !== 'reservation'), 'Failed question consumes no completed turn');
  assert(!(storeAfterFailure.researchCreditsByUserID?.[auth.accountUserID] || []).some(item => item.units < 0), 'Failure consumes no purchased credit');
  const listed = await request('/research/conversations/list', { auth }, token);
  assert(listed.body.conversations.some(item => item.id === conversationID && item.messageCount === 1), JSON.stringify(listed.body));
  const conflicting = await request('/research/conversations/message', { auth, conversationID, question: 'Different question', requestID }, token);
  assert.equal(conflicting.body.code, 'RESEARCH_REQUEST_ID_CONFLICT');
  process.env.PERMITEXT_TEST_RESEARCH_MOCK = '1';
  const retry = await request('/research/conversations/message', { auth, conversationID, question, requestID }, token);
  assert.equal(retry.status, 200, JSON.stringify(retry.body));
  assert.equal(retry.body.conversation.messages.length, 2);
  assert.equal(retry.body.conversation.messages.filter(item => item.role === 'user').length, 1);
  assert.equal(retry.body.conversation.messages[0].failure, undefined);
  assert.equal(retry.body.conversation.messages[0].requestID, requestID);
  const replay = await request('/research/conversations/message', { auth, conversationID, question, requestID }, token);
  assert.equal(replay.body.replayed, true);
  assert.equal(replay.body.conversation.messages.length, 2);
  const legacyCreated = await request('/research/conversations/create', { auth }, token);
  const legacyID = legacyCreated.body.conversation.id;
  const retainedBody = { auth, conversationID: legacyID, requestID: 'original-phone-id', question: 'Preserve this existing phone question', contextRevision: 0, startedAt: new Date(Date.now() - 60_000).toISOString(), failureCode: 'FORGED_SERVER_FAILURE' };
  const wrongContext = await request('/research/conversations/retain-interrupted-question', { ...retainedBody, contextRevision: 99 }, token);
  assert.equal(wrongContext.body.code, 'RESEARCH_CONTEXT_CHANGED');
  const retained = await request('/research/conversations/retain-interrupted-question', retainedBody, token);
  assert.equal(retained.status, 200, JSON.stringify(retained.body));
  assert.equal(retained.body.charged, false);
  assert.equal(retained.body.conversation.messages.length, 1);
  assert.equal(retained.body.conversation.messages[0].failure.origin, 'client-recovery');
  assert.equal(retained.body.conversation.messages[0].failure.code, 'RESEARCH_INTERRUPTED');
  assert.equal(retained.body.conversation.messages[0].requestID, 'original-phone-id');
  const retainedAgain = await request('/research/conversations/retain-interrupted-question', retainedBody, token);
  assert.equal(retainedAgain.body.replayed, true);
  assert.equal(retainedAgain.body.conversation.revision, retained.body.conversation.revision);
  const retainedConflict = await request('/research/conversations/retain-interrupted-question', { ...retainedBody, question: 'Different local question' }, token);
  assert.equal(retainedConflict.body.code, 'RESEARCH_REQUEST_ID_CONFLICT');
  const other = await request('/account/sign-in', { credential: { provider: 'web', providerUserID: randomUUID(), displayName: 'Other fixture account' } });
  const denied = await request('/research/conversations/retain-interrupted-question', { ...retainedBody, auth: { accountUserID: other.body.account.appUserID } }, other.body.account.backendSessionToken);
  assert.notEqual(denied.status, 200, 'Another account cannot retain history in the owner conversation');
  const completedRetain = await request('/research/conversations/retain-interrupted-question', { auth, conversationID, requestID, question, contextRevision: 0 }, token);
  assert.equal(completedRetain.status, 200);
  assert.equal(completedRetain.body.retained, false);
  assert.equal(completedRetain.body.conversation.messages.length, 2);
  assert.equal(completedRetain.body.conversation.messages[0].failure, undefined);
  console.log('Failed-question history contract passed: first failure list/get, cross-client recovery, same-ID retry/replay, no duplicate messages, no external provider calls.');
} finally {
  if (server) { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); }
  globalThis.fetch = actualFetch;
  await rm(scratch, { recursive: true, force: true });
}
