import assert from 'node:assert/strict';
import { answerRequest, readResearchAnswerStream, fastResearchInterpretation } from '../research-fast-stream.mjs';
import { reportItemPreview } from '../report-presentation.mjs';
const source={sourceID:'p1',sectionID:'1',sectionNumber:'101.1',codePrefix:'BC',codeEdition:'2022',text:'Code title.'};
const sources=[{id:'S1',text:source.text}];
const encode=events=>{const bytes=new TextEncoder().encode(events.map(e=>`data: ${JSON.stringify(e)}\r\n\r\n`).join(''));return new ReadableStream({start(c){for(let i=0;i<bytes.length;i+=3)c.enqueue(bytes.slice(i,i+3));c.close();}});};
const text='Café → [S1]';
const delta={type:'response.output_text.delta',delta:text};
const done={type:'response.completed',response:{status:'completed',output:[{content:[{type:'output_text',text}]}],usage:{input_tokens:3,output_tokens:4}}};
let visible='';const payload=await readResearchAnswerStream(encode([delta,done]),{onText:t=>visible+=t});
assert.equal(visible,text);assert.equal(payload.usage.output_tokens,4);
await assert.rejects(readResearchAnswerStream(encode([delta])),/before a completed answer/);
await assert.rejects(readResearchAnswerStream(encode([delta,{...done,response:{...done.response,output:[]}}])),/consistently/);
await assert.rejects(readResearchAnswerStream(encode([{type:'response.refusal.delta'}])),/did not complete/);
const controller=new AbortController();controller.abort();await assert.rejects(readResearchAnswerStream(encode([delta,done]),{signal:controller.signal}),{name:'AbortError'});
const answer=fastResearchInterpretation(text,[source],sources);
assert.equal(answer.citations[0].sourceIDs[0],'p1');assert.equal(answer.verification.pass,false);
const unknown=fastResearchInterpretation('Invented citation [S99]',[source],sources);
assert.equal(unknown.citations.length,0);assert.deepEqual(unknown.citationIdentity.unknown,['S99']);
const preview=reportItemPreview({kind:'researchAnswer',question:'Title?',...answer,includeResearchMetadata:false});
assert.ok(preview.some(p=>p.label==='Answer status'&&p.text.includes('Unreviewed')));
assert.ok(preview.some(p=>p.text===text),'Report retains the entire fast answer');
assert.equal(answerRequest('Explain',sources).model,'gpt-6-luna');
console.log('PASS fast stream: Unicode chunks, terminal consistency, refusal, cancellation, citation identity and report status.');
