// Run against a fresh disposable populated-workspace-performance-fixture.mjs server.
import assert from 'node:assert/strict';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const fixtureURL = new URL(process.env.PERMITEXT_UX_FIXTURE_URL);
assert.equal(fixtureURL.hostname,'127.0.0.1');
const browser = await chromium.launch({headless:true,
  executablePath:process.env.CHROMIUM_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
try {
  const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'reduce'});
  page.setDefaultTimeout(15000);
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(fixtureURL.href);
  await page.getByRole('button',{name:'Notebook',exact:true}).click();
  await page.getByRole('menuitemradio',{name:'Synthetic Project 1',exact:true}).click();
  const index=page.locator('.notebook-index-panel');
  const list=index.getByRole('region',{name:'Project notes'});
  const selected=page.locator('.notebook-panel:visible');
  await selected.locator('.bn-editor').waitFor();
  assert.equal(await page.locator('.workspace-panel:visible').count(),3);
  assert.equal(await list.locator('li').count(),4);
  const evidence=page.locator('.saved-panel:visible');
  const menuSpacing=await page.evaluate(() => ['.saved-panel','.notebook-index-panel'].map(selector=>{
    const panel=document.querySelector(selector), button=panel.querySelector('.column-group-menu-button, .notebook-index-menu-button');
    const bounds=panel.getBoundingClientRect(), rect=button.getBoundingClientRect();
    return {top:rect.top-bounds.top,right:bounds.right-rect.right,width:rect.width,height:rect.height};
  }));
  for (const edge of ['top','right','width','height']) assert.ok(Math.abs(menuSpacing[0][edge]-menuSpacing[1][edge])<1,`Notes menu ${edge} matches Evidence.`);
  const evidenceNode=await evidence.elementHandle();
  const indexNode=await index.elementHandle();
  let evidenceBounds=await evidence.boundingBox(), listBounds=await index.boundingBox(), editorBounds=await selected.boundingBox();
  assert.ok(evidenceBounds.x < listBounds.x && listBounds.x < editorBounds.x);
  assert.ok(editorBounds.x+editorBounds.width<=1441);

  await list.getByRole('button',{name:'Synthetic Note 1',exact:true}).click();
  await selected.locator('.bn-editor').waitFor();
  assert.equal(await list.locator('[aria-current=true]').innerText(),'Synthetic Note 1');
  assert.equal(await selected.locator('.panel-kind').first().textContent(),'Synthetic Note 1');
  const editor=selected.locator('.bn-editor');
  const editorNode=await editor.elementHandle();
  const saved=page.waitForResponse(response=>new URL(response.url()).pathname==='/notebook/cards/save' && response.ok());
  await editor.click();
  await page.keyboard.press('ControlOrMeta+End');
  await page.keyboard.press('Enter');
  await page.keyboard.insertText('Notebook draft retention check.');
  await saved;
  await list.getByRole('button',{name:'Synthetic Note 2',exact:true}).click();
  assert.equal(await page.locator('.notebook-panel:visible').count(),1);
  await list.getByRole('button',{name:'Synthetic Note 1',exact:true}).click();
  await editor.waitFor();
  assert.equal(await editor.evaluate((node,retained)=>node===retained,editorNode),true);
  assert.match(await editor.innerText(),/Notebook draft retention check/);
  assert.equal(await evidence.evaluate((node,retained)=>node===retained,evidenceNode),true);
  assert.equal(await index.evaluate((node,retained)=>node===retained,indexNode),true);

  const indexID=await index.getAttribute('data-pane-id');
  const editorID=await selected.getAttribute('data-pane-id');
  const divider=page.locator(`.pane-divider[data-previous-pane-id="${indexID}"][data-next-pane-id="${editorID}"]`);
  const handle=await divider.boundingBox();
  listBounds=await index.boundingBox();editorBounds=await selected.boundingBox();
  await page.mouse.move(handle.x+handle.width/2,handle.y+100);
  await page.mouse.down();
  await page.mouse.move(handle.x+handle.width/2+60,handle.y+100,{steps:6});
  await page.mouse.up();
  const resized=await index.boundingBox();
  assert.ok(resized.width>listBounds.width+40,'The middle/editor divider increases the list width.');
  assert.ok((await selected.boundingBox()).width<editorBounds.width-40,'The editor shares the resize.');
  assert.ok(Math.abs((await evidence.boundingBox()).width-evidenceBounds.width)<2,'Resizing the list keeps Evidence in place.');
  for (const panel of [evidence,index,selected]) {
    await panel.locator('.panel-kind').first().click();
    assert.equal(await panel.evaluate(node=>node.classList.contains('is-collapsed')),false);
    assert.equal(await panel.locator(':scope > header').getByRole('button',{name:/^(Collapse|Expand) /}).count(),0);
  }
  assert.equal(await page.getByRole('button',{name:'Collapse all',exact:true}).isVisible(),false);
  assert.equal(await page.getByRole('button',{name:'Expand all',exact:true}).isVisible(),false);
  assert.ok(Math.abs((await index.boundingBox()).width-resized.width)<2);
  assert.match(await editor.innerText(),/Notebook draft retention check/);
  if (process.env.PERMITEXT_UX_SCREENSHOT) await page.screenshot({path:process.env.PERMITEXT_UX_SCREENSHOT});
  await page.getByRole('button',{name:'Research',exact:true}).click();
  await page.getByRole('button',{name:'Notebook',exact:true}).click();
  assert.equal(await editor.evaluate((node,retained)=>node===retained,editorNode),true);
  await page.reload();
  await selected.locator('.bn-editor').waitFor();
  assert.equal(await page.locator('.workspace-panel.is-collapsed:visible').count(),0);
  assert.match(await selected.locator('.bn-editor').innerText(),/Notebook draft retention check/);
  assert.equal(await list.locator('[aria-current=true]').innerText(),'Synthetic Note 1');
  assert.ok(Math.abs((await index.boundingBox()).width-resized.width)<2,'Resized list width survives refresh.');
  await list.getByRole('button',{name:'New note',exact:true}).click();
  await list.getByRole('button',{name:'Untitled',exact:true}).waitFor();
  assert.equal(await list.locator('li').count(),5);
  assert.equal(await list.locator('[aria-current=true]').innerText(),'Untitled');
  await list.getByRole('button',{name:'Synthetic Note 1',exact:true}).click();
  assert.match(await selected.locator('.bn-editor').innerText(),/Notebook draft retention check/);
  const options=index.getByRole('button',{name:'Notes options',exact:true});
  await options.click();
  await page.getByRole('menuitem',{name:'Select notes',exact:true}).click();
  assert.equal(await list.getByRole('checkbox').count(),5);
  await list.getByRole('checkbox',{name:'Synthetic Note 2',exact:true}).click();
  await list.getByRole('checkbox',{name:'Synthetic Note 3',exact:true}).click();
  await list.getByText('2 selected',{exact:true}).waitFor();
  await options.click();
  await page.getByRole('menuitem',{name:'Select all',exact:true}).click();
  assert.equal(await list.locator('[role="checkbox"][aria-checked="true"]').count(),5);
  await options.click();
  await page.getByRole('menuitem',{name:'Deselect all',exact:true}).click();
  assert.equal(await list.locator('[role="checkbox"][aria-checked="true"]').count(),0);
  await list.getByRole('checkbox',{name:'Synthetic Note 2',exact:true}).click();
  await list.getByRole('checkbox',{name:'Synthetic Note 3',exact:true}).click();
  await options.click();
  await page.getByRole('menuitem',{name:'Move selected notes to Trash',exact:true}).click();
  const confirmation=page.getByRole('alertdialog',{name:'Move selected Notes to Trash?',exact:true});
  await confirmation.getByRole('button',{name:'Cancel',exact:true}).click();
  assert.equal(await list.getByRole('checkbox').count(),5);
  assert.equal(await list.locator('[aria-checked="true"]').count(),2);
  await options.click();
  await page.getByRole('menuitem',{name:'Move selected notes to Trash',exact:true}).click();
  await confirmation.getByRole('button',{name:'Move to Trash',exact:true}).click();
  await list.getByRole('button',{name:'Synthetic Note 4',exact:true}).waitFor();
  assert.equal(await list.locator('li').count(),3);
  assert.equal(await list.getByText('Synthetic Note 2',{exact:true}).count(),0);
  assert.equal(await list.getByText('Synthetic Note 3',{exact:true}).count(),0);
  assert.match(await selected.locator('.bn-editor').innerText(),/Notebook draft retention check/);
  await page.reload();
  await list.getByRole('button',{name:'Synthetic Note 1',exact:true}).waitFor();
  assert.equal(await list.locator('li').count(),3,'Bulk Trash persists after refresh without removing unselected notes.');
  assert.deepEqual(errors,[]);
  console.log('Notebook desk passed: Evidence/list/editor order, retained edits, noncollapsing columns, divider drag, persisted width/selection, new-note action and selective bulk Trash with cancellation.');
} finally {await browser.close();}
