import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
import {nycMappedFactFields} from '../public/nyc-property-facts.js';
const source = await readFile(new URL('../public/app.js',import.meta.url),'utf8');
const extract = name => {
 const start=source.indexOf(`function ${name}(`), end=source.indexOf('\n}',start);
 assert.ok(start>=0 && end>start); return source.slice(start,end+2);
};
const factStart=source.indexOf('const projectStructuredFactGroups = ');
const factEnd=source.indexOf('\n];',factStart)+3;
const facts=vm.createContext({nycMappedFactFields});
vm.runInContext(source.slice(factStart,factEnd)+'\n'+extract('projectFactPresentationGroups')+'\nglobalThis.original = projectStructuredFactGroups;',facts);
const grouped=facts.projectFactPresentationGroups();
assert.deepEqual(Array.from(grouped,g=>g.label),['Property','Building','Work & code basis','Zoning','Special designations']);
const before=Array.from(facts.original.flatMap(g=>g.fields),f=>f.key).sort();
const after=Array.from(grouped.flatMap(g=>g.fields),f=>f.key).sort();
assert.deepEqual(after,before,'Regrouping never drops or duplicates canonical/imported fields');
assert.equal(grouped[0].fields.find(f=>f.key==='address').projectAddress,true);
assert.deepEqual(Array.from(grouped[2].fields,f=>f.key),['project-status','work-filing-type','code-basis']);
const old='research:conversation:compare', next='utility:analysis:conversation-compare';
const state={researchConversationID:'primary',utilityInstances:[{id:'existing',key:'analysis',conversationID:'existing',draft:'Retained draft'}],paneOrder:['reader:a',old,'reader:b'],paneWeights:{[old]:1100},collapsedPaneIDs:[old],pinnedPaneID:old,workflowMembership:{[old]:['notebook']},columnGroups:[{paneIDs:[old],columns:{[old]:{kind:'research'}}}]};
const context=vm.createContext({state,supplementalResearchConversationIDs:['primary','existing','compare'],researchConversationPaneIsOpen:()=>true,newUtilityInstance:(key,options)=>({key,...options}),paneIDForUtilityInstance:instance=>`utility:${instance.key}:${instance.id}`});
vm.runInContext(extract('restoreAssistantConversationOwners'),context);
context.restoreAssistantConversationOwners();
assert.deepEqual(Array.from(state.paneOrder),['reader:a',next,'reader:b']);
assert.equal(state.utilityInstances.length,2);
assert.equal(state.utilityInstances[0].draft,'Retained draft');
assert.equal(state.paneWeights[next],1100); assert.equal(state.paneWeights[old],undefined);
assert.equal(state.pinnedPaneID,next); assert.equal(state.collapsedPaneIDs[0],next);
assert.deepEqual(state.workflowMembership[next],['notebook']);
assert.equal(state.columnGroups[0].paneIDs[0],next);
assert.equal(state.columnGroups[0].columns[next].value,state.utilityInstances[1]);
const snapshot=JSON.stringify(state); context.restoreAssistantConversationOwners();
assert.equal(JSON.stringify(state),snapshot,'Repeated layout hydration does not duplicate or move conversation owners');
console.log('Workflow simplification passed: complete fact regrouping and conversation-owner migration retains order, widths, grouping, drafts and view membership.');
