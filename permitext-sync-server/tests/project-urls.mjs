import assert from 'node:assert/strict';
import {buildProjectWorkspaceURL, createProjectURLCatalog, mergeProjectURLNames, parseProjectWorkspaceURL, projectURLSlug} from '../public/project-urls.js';
import {parseCodeQuestionDeepLink} from '../public/code-question-workspace.js';
const date = n => `2026-01-${String(n).padStart(2,'0')}T00:00:00.000Z`;
const a = {projectID:'a', name:'Courtyard House', createdAt:date(1), updatedAt:date(4)};
const b = {projectID:'b', name:'Courtyard House', createdAt:date(2), updatedAt:date(2)};
let names = [{projectID:'a', name:'Original Name', claimedAt:date(1)}, {projectID:'a', name:a.name, claimedAt:date(4)},
  {projectID:'b', name:b.name, claimedAt:date(2)}];
let catalog = createProjectURLCatalog([a,b], names);
assert.equal(catalog.slugFor('b'), 'courtyard-house', 'The first claim keeps its existing bookmark, even if the renamed Project is older.');
assert.match(catalog.slugFor('a'), /^courtyard-house-[a-z0-9]{6}$/);
assert.equal(catalog.resolve('original-name').projectID, 'a');
const oldA = catalog.slugFor('a');
const renamed = {...a, name:'100 Main Street', updatedAt:date(5)};
names = mergeProjectURLNames(names, [{projectID:'a', name:renamed.name, claimedAt:date(5)}]);
catalog = createProjectURLCatalog([renamed,b], names);
assert.equal(catalog.slugFor('a'), '100-main-street');
assert.equal(catalog.resolve(oldA).projectID, 'a', 'A previous duplicate-name URL remains valid after another rename.');
assert.equal(catalog.resolve('original-name').projectID, 'a');
assert.equal(catalog.resolve('courtyard-house').projectID, 'b');
const deleted = createProjectURLCatalog([{...renamed, deletedAt:date(6)},b,{projectID:'c',name:'Original Name',createdAt:date(7)}], names);
assert.equal(deleted.resolve('original-name').projectID, 'a', 'A deleted Project URL must not be reassigned to a different Project.');
assert(deleted.resolve('original-name').deletedAt);
assert.notEqual(deleted.slugFor('c'), 'original-name');
assert.equal(projectURLSlug('  Café / Résumé & Site #2  '), 'cafe-resume-site-2');
assert.equal(projectURLSlug('東京の計画'), '東京の計画');
assert.equal(projectURLSlug('...'), 'project');
assert.equal(projectURLSlug('a'.repeat(100)).length, 80);
const long = createProjectURLCatalog([{projectID:'x',name:'a'.repeat(100),createdAt:date(1)},{projectID:'y',name:'a'.repeat(100),createdAt:date(2)}]);
assert.equal(parseProjectWorkspaceURL(new URL(buildProjectWorkspaceURL(long.slugFor('y')), 'https://per.codes')).slug, long.slugFor('y'));
assert.deepEqual(parseProjectWorkspaceURL(new URL('/workspace/100-main-street/', 'https://per.codes')), {slug:'100-main-street'});
for (const path of ['/workspace','/workspace/a/b','/workspace/%ZZ','/workspace/%2F','/workspace/-a','/workspace/a-']) assert.equal(parseProjectWorkspaceURL({pathname:path}), null);
assert.equal(parseCodeQuestionDeepLink('#cq/project/web-project-old').projectID, 'web-project-old');
assert.equal(parseCodeQuestionDeepLink('#cq/project/%ZZ'), null);
console.log('Project URLs passed: readable names, Unicode, duplicates, rename aliases, reserved deleted names, long names, and legacy links.');
