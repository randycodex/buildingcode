import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {pathToFileURL,fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
const directory=dirname(fileURLToPath(import.meta.url)),publicRoot=resolve(directory,'../../public');
const code=(await readFile(resolve(directory,'public/library-core.js'),'utf8')).replace(/from '(\/web\/[^']+)'/g,(_,name)=>`from '${pathToFileURL(resolve(publicRoot,name.slice(5))).href}'`);
const {intersect,evaluateSearch,documentRecord,searchWords,searchWordForms}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
assert.deepEqual(intersect([[9,3,1].sort((a,b)=>a-b),[1,2,3],[3,4]]),[3]);
assert.deepEqual(intersect([[1,2],[]]),[]);
const {defaultSyncCodeVersion}=await import('../../public/sync-identity.js');
const source={canonicalEdition:defaultSyncCodeVersion,jurisdictionID:1,codeID:1,categoryID:2,codePrefix:'BC'};
const metadata={codeSources:[source]};
const chapter={id:10,codePrefix:'BC',codeVersion:defaultSyncCodeVersion,codeSectionID:2,chapterNumber:'10'};
const records=[documentRecord({id:1,sectionNumber:'1010.1',title:'Exit doors.',blocks:[{plainText:'Doors leading to an exit or exits.'}]},chapter),documentRecord({id:2,sectionNumber:'1010.2',title:'Dead-end corridors.',blocks:[{plainText:'A dead-end corridor shall meet this rule.'}]},chapter),documentRecord({id:3,sectionNumber:'1010.3',title:'Water supply.',blocks:[{plainText:'A water supply is required.'}]},chapter)];
const run=(q,extra={})=>evaluateSearch(records,new URL('https://local/code/search?'+new URLSearchParams({q,match:'words',version:'all',limit:'25',...extra})),metadata);
assert.equal(run('exit').totalResults,1);assert.equal(run('exits').totalResults,1);assert.equal(run('dead end corridor').results[0].id,2);
assert.equal(run('water supply').results[0].codeSource.canonicalEdition,defaultSyncCodeVersion);
assert.equal(run('water supply',{code:'PC'}).totalResults,0);
assert.equal(run('water supply',{sourceScope:JSON.stringify({version:1,enabledSources:[]})}).totalResults,0);
assert.equal(run('water supply',{sourceScope:JSON.stringify({version:1,enabledSources:[source]})}).totalResults,1);
assert.throws(()=>run('water supply',{sourceScope:'broken'}));
assert.equal(run('water supply',{version:'wrong edition'}).totalResults,0);
assert.equal(run('water supply',{match:'exact'}).totalResults,1);
assert.equal(run('supply water',{match:'exact'}).totalResults,0);
assert.equal(run('1010.2').results[0].id,2);
assert.deepEqual(searchWords('dead-end corridor'),['dead','end','corridor']);assert.deepEqual(searchWordForms('exits'),['exits','exit']);
assert.equal(run('water',{grouped:'true'}).groups[0].cursorKind,'offset');
console.log('Prototype core: words, phrase boundaries, identifier lookup, source/edition filters, grouping and posting intersection passed.');
